"""Turns the legacy workbook into a golden-test fixture.

Every payroll row is exported with the inputs the engine needs and the values the
workbook produced, so the pure calculator can be checked cell-for-cell against
what the business actually paid.

Run: python3 tools/build_golden_fixture.py
"""

from __future__ import annotations

import json
import pathlib

import openpyxl

SOURCE = pathlib.Path("/home/mahmoud/Master Payroll (corrected tax + PoD flag).xlsx")
OUT = pathlib.Path(__file__).resolve().parent.parent / "sharm_dreams_group" / "tests" / "golden_payroll.json"

# column indices in the legacy sheet
COL = {
	"work_id": 2,  # B  Work ID#
	"name": 3,  # C  Colleague Name En
	"name_ar": 4,  # D  Colleague Name Ar
	"company": 5,  # E  Company (Arabic)
	"position": 7,  # G
	"department": 8,  # H
	"location": 9,  # I
	"national_id": 10,  # J
	"si_number": 11,  # K
	"date_of_joining": 12,  # L
	"date_of_birth": 14,  # N
	"delegated_company": 6,  # F
	"gross": 16,  # P
	"total_earning": 28,  # AB
	"penalties": 30,  # AD
	"absenteeism": 32,  # AF
	"total_deductions": 33,  # AG
	"life_insurance": 34,  # AH
	"medical_insurance": 35,  # AI
	"final_limit": 36,  # AJ
	"si_employee": 37,  # AK
	"tax_base": 38,  # AL
	"base_rounded": 39,  # AM
	"cap_15pct": 40,  # AN
	"annual_premium": 41,  # AO
	"insurance_deductible": 42,  # AP
	"annual_taxable": 43,  # AQ
	"tax": 44,  # AR
	"martyrs": 45,  # AS
	"total_ded": 46,  # AT
	"net_salary": 47,  # AU
	"si_employer": 56,  # BD
	"emergency": 57,  # BE
	"training_fund": 59,  # BG
	"people_of_determination": 62,  # BJ
}

FIRST_ROW, LAST_ROW = 3, 209


def num(value) -> float:
	try:
		return float(value or 0)
	except (TypeError, ValueError):
		return 0.0


def main() -> None:
	# data_only=True gives the cached values Excel last computed, which is the
	# arithmetic the business actually paid - not our re-reading of the formulas.
	wb = openpyxl.load_workbook(SOURCE, data_only=True)
	ws = wb.active

	rows = []
	for r in range(FIRST_ROW, LAST_ROW + 1):
		gross = num(ws.cell(r, COL["gross"]).value)
		if gross == 0:
			continue
		rows.append(
			{
				"row": r,
				"work_id": str(ws.cell(r, COL["work_id"]).value or "").strip(),
				"name": str(ws.cell(r, COL["name"]).value or "").strip(),
				"name_ar": str(ws.cell(r, COL["name_ar"]).value or "").strip(),
				"company": str(ws.cell(r, COL["company"]).value or "").strip(),
				"position": str(ws.cell(r, COL["position"]).value or "").strip(),
				"department": str(ws.cell(r, COL["department"]).value or "").strip(),
				"location": str(ws.cell(r, COL["location"]).value or "").strip(),
				"national_id": str(ws.cell(r, COL["national_id"]).value or "").strip(),
				"si_number": str(ws.cell(r, COL["si_number"]).value or "").strip(),
				"delegated_company": str(ws.cell(r, COL["delegated_company"]).value or "").strip(),
				"is_person_of_determination": str(ws.cell(r, COL["people_of_determination"]).value or "")
				.strip()
				.lower()
				== "yes",
				"gross": gross,
				"total_earning": num(ws.cell(r, COL["total_earning"]).value),
				"total_deductions": num(ws.cell(r, COL["total_deductions"]).value),
				"life_insurance": num(ws.cell(r, COL["life_insurance"]).value),
				"medical_insurance": num(ws.cell(r, COL["medical_insurance"]).value),
				"final_limit": num(ws.cell(r, COL["final_limit"]).value),
				"expected_tax_base": num(ws.cell(r, COL["tax_base"]).value),
				"expected_base_rounded": num(ws.cell(r, COL["base_rounded"]).value),
				"expected_insurance_deductible": num(ws.cell(r, COL["insurance_deductible"]).value),
				"expected_annual_taxable": num(ws.cell(r, COL["annual_taxable"]).value),
				"expected_tax": num(ws.cell(r, COL["tax"]).value),
				"expected_martyrs": num(ws.cell(r, COL["martyrs"]).value),
				"expected_si_employee": num(ws.cell(r, COL["si_employee"]).value),
				"expected_si_employer": num(ws.cell(r, COL["si_employer"]).value),
				"expected_emergency": num(ws.cell(r, COL["emergency"]).value),
				"expected_training_fund": num(ws.cell(r, COL["training_fund"]).value),
				"expected_total_deductions": num(ws.cell(r, COL["total_ded"]).value),
				"expected_net_salary": num(ws.cell(r, COL["net_salary"]).value),
			}
		)

	payload = {
		"_note": (
			"Generated by tools/build_golden_fixture.py from the legacy workbook. "
			"expected_* are what the workbook actually paid; the tests assert the "
			"engine reproduces them.  Do not hand edit."
		),
		"rows": rows,
	}
	OUT.parent.mkdir(parents=True, exist_ok=True)
	OUT.write_text(json.dumps(payload, indent=1))

	print(f"wrote {OUT}")
	print(f"  rows with a gross      {len(rows)}")
	print(f"  delegated rows         {sum(1 for r in rows if r['delegated_company'])}")
	print(f"  people of determination {sum(1 for r in rows if r['is_person_of_determination'])}")
	print(f"  rows with income tax   {sum(1 for r in rows if r['expected_tax'] > 0)}")
	print(f"  rows with loans        {sum(1 for r in rows if r['expected_total_deductions'] > 0)}")


if __name__ == "__main__":
	main()
